export const words = code => WORDS[code] || (/^[a-z_]+$/.test(code || "") ? "Something went wrong (" + code + ")." : code || "Something went wrong.");

export class ApiError extends Error { constructor(code) { super(words(code)); this.code = code; } }
const unwrap = r => { if (!r || !r.ok) throw new ApiError(r ? r.error : "offline"); return r.data; };

export const api = {
  state: async () => unwrap(await sky.social.state()),
  signUp: async (e, p) => unwrap(await sky.social.signUp(e, p)),
  signIn: async (e, p) => unwrap(await sky.social.signIn(e, p)),
  signOut: async () => unwrap(await sky.social.signOut()),
  reset: async e => unwrap(await sky.social.reset(e)),
  rpc: async (fn, args) => unwrap(await sky.social.rpc(fn, args)),
  screens: async () => unwrap(await sky.social.screens()),
  upload: async (kind, bytes) => unwrap(await sky.social.upload(kind, bytes)),
  removeMedia: async url => unwrap(await sky.social.removeMedia(url)),
  attach: async (target, name, bytes) => unwrap(await sky.social.attach(target, name, bytes)),   // a friend's id, or "srv:<server id>"
  fileUrls: async paths => unwrap(await sky.social.fileUrls(paths)),
  shareSource: async id => unwrap(await sky.social.shareSource(id)),
  idle: async () => unwrap(await sky.social.idle()),
  notify: n => sky.social.notify(n),
};
